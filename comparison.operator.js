// > COMPARISON OPERATOR
// Operator pembanding yang menghasilkan nilai akhir berupa boolean (true or false)
// >, <, >=, <=, ==, ===, !==

console.log(5 > 10); // false
console.log(10 < 100); // true
console.log(5 >= 5); // true 

// ==   : Pengecekan value saja
// ===  : Pengecekan value dan juga tipe data 
console.log(5 == '5'); // true
console.log(5 === '5'); // false

console.log(5 != '5'); // false
console.log(5 !== '5') // true