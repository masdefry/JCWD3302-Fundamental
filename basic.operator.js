// > BASIC OPERATOR
// +, -, *, /, %

// +
const number1 = 10;
const number2 = 20;
console.log(number1 + number2);
// -
console.log(100 - 50);
// *
console.log(5 * 5);
// /
console.log(100 / 4);
// % 
console.log(10 % 3); // 1
console.log(10 % 4); // 2
console.log(6 % 5); // 1

// Special cases
const num1 = 10;
const num2 = '5';
console.log(num1 + num2); // 105 (string concatenation)
console.log(num1 - num2); // 5 (number subtraction)
console.log(num1 * num2); // 50 (number multiplication)
console.log(num1 / num2); // 2 (number division)